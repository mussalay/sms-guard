def build_custom_ru(path: Path) -> None:
    if len(SAFE) < 50 or len(FRAUD) < 50:
        raise ValueError("Нужно не менее 100 искусственных SMS")
    records = []
    for label, examples in ((0, SAFE), (1, FRAUD)):
        for category, text in examples:
            if re.search(r"\d{7,}|[\w.+-]+@[\w.-]+", text):
                raise ValueError("Недопустимые идентификаторы в искусственном сообщении")
            records.append(
                {
                    "id": f"ru-{len(records) + 1:03d}",
                    "text": text,
                    "label": label,
                    "language": "ru",
                    "scenario": category,
                    "annotation_author": AUTHOR,
                    "split": "test_only",
                    "synthetic": True,
                }
            )
    if len({row["text"] for row in records}) != len(records):
        raise ValueError("Повторные искусственные сообщения")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as target:
        writer = csv.DictWriter(target, fieldnames=list(records[0]))
        writer.writeheader()
        writer.writerows(records)


if __name__ == "__main__":
    build_custom_ru(Path(__file__).resolve().parents[2] / "data/raw/custom_ru.csv")
